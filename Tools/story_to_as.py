"""One-off converter: Story v1 JSON (story.json and dev fixtures) -> AngelScript story sources.

The generated files are the source of truth afterwards; edit them by hand, do not regenerate over edits.

    python Tools/story_to_as.py [--output Resources/DeathLovers/Story/Script]
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STORY = ROOT / "Resources/DeathLovers/Story"

HEADER = "//\n// Created by Claude on 27.11.2026.\n// Generated by Tools/story_to_as.py from {source}; edit by hand from now on.\n//\n"

# label -> output file, in emission order
MAIN_FILES = {
    "Prologue.as": ["label_prologue", "start", "main_choice"],
    "Landfill.as": ["label_landfill"],
    "Offices.as": ["label_offices"],
    "Canteen.as": ["label_canteen"],
    "Endings.as": ["ending", "plague_ending", "war_ending", "hunger_ending", "plaguewar_ending",
                   "plaguehunger_ending", "warhunger_ending", "harem_ending", "bad_ending"],
}

DEFAULT_DISSOLVE = 0.15


class ConvertError(Exception):
    pass


def literal(text):
    return json.dumps(text, ensure_ascii=False)


def number(value):
    value = float(value)
    return str(int(value)) if value.is_integer() else repr(value)


def speaker_name(speaker_id):
    return speaker_id[3:] if speaker_id.startswith("ch_") else speaker_id


def variable_name(variable_id):
    return variable_id[4:] if variable_id.startswith("var_") else variable_id


def transition(node, default_kind=None, default_seconds=None):
    kind = node.get("kind", "none")
    seconds = node.get("seconds")
    if kind == "none":
        return None
    if kind == default_kind and seconds == default_seconds:
        return ""
    return "{}({})".format(kind, "" if seconds is None else number(seconds))


def expression(node, parent=None):
    op = node["op"]
    if op == "literal":
        value = node["value"]
        return ("true" if value else "false") if isinstance(value, bool) else str(value)
    if op == "variable":
        return "v." + variable_name(node["variableId"])
    if op == "not":
        inner = expression(node["operand"], "not")
        return "!" + (inner if node["operand"]["op"] in ("variable", "literal", "not") else "(" + inner + ")")
    if op in ("and", "or"):
        joined = (" && " if op == "and" else " || ").join(expression(item, op) for item in node["operands"])
        return "(" + joined + ")" if parent in ("and", "or", "not") and parent != op else joined
    operators = dict(eq="==", ne="!=", lt="<", le="<=", gt=">", ge=">=")
    if op not in operators:
        raise ConvertError("Unsupported condition operator " + op)
    return "{} {} {}".format(expression(node["left"], op), operators[op], expression(node["right"], op))


class Story:
    def __init__(self, document, prefix=""):
        self.commands = document["commands"]
        self.labels = document["labels"]
        self.variables = document.get("variables", {})
        self.prefix = prefix
        self.label_at = {entry: name for name, entry in self.labels.items()}
        self.never_returns = self.compute_never_returns()

    def function(self, label):
        return self.prefix + label

    def successors(self, node):
        command = self.commands[node]
        kind = command["type"]
        if kind in ("Return", "RestartToMenu", "Jump"):
            return []
        if kind == "Branch":
            return [command["trueTarget"], command["falseTarget"]]
        if kind == "Choice":
            return [option["target"] for option in command["options"]]
        if kind == "Call":
            return [command["returnTarget"]]
        return [command["next"]] if command.get("next") else []

    def region(self, label):
        """Nodes of one label: reachable from its entry without entering another label."""
        entry = self.labels[label]
        seen, pending = set(), [entry]
        while pending:
            node = pending.pop()
            if node in seen or (node != entry and node in self.label_at):
                continue
            seen.add(node)
            pending.extend(self.successors(node))
        return seen

    def compute_never_returns(self):
        """A label never returns when no Return is reachable and every exit is a restart or a never-returning jump."""
        result = {label: True for label in self.labels}
        changed = True
        while changed:
            changed = False
            for label in self.labels:
                if not result[label]:
                    continue
                for node in self.region(label):
                    command = self.commands[node]
                    exits = []
                    if command["type"] == "Return" or (not self.successors(node) and command["type"] not in ("RestartToMenu", "Jump")):
                        exits.append(None)
                    if command["type"] == "Jump":
                        exits.append(self.label_at.get(command["target"]))
                    for successor in self.successors(node):
                        if successor != self.labels[label] and successor in self.label_at:
                            exits.append(self.label_at[successor])
                    if any(target is None or not result[target] for target in exits):
                        result[label] = False
                        changed = True
                        break
        return result


class Emitter:
    def __init__(self, story, label):
        self.story = story
        self.label = label
        self.entry = story.labels[label]
        self.emitted = set()
        self.loop = False
        # every menu of a function gets its own name: AngelScript forbids redeclaring a local in one scope
        self.menu_count = 0

    def transfer(self, target, indent):
        if target == self.entry:
            self.loop = True
            return [indent + "continue;"]
        if target not in self.story.label_at:
            raise ConvertError("{}: jump into the middle of a label ({})".format(self.label, target))
        name = self.story.function(self.story.label_at[target])
        if self.story.never_returns[self.story.label_at[target]]:
            return [indent + "jump({});".format(name)]
        # Ren'Py jump keeps the call stack: the jumped-to label returns to our caller.
        return [indent + "call({});".format(name), indent + "return;"]

    def say(self, command):
        speaker = speaker_name(command["speakerId"])
        text = literal(command["normalizedText"])
        if command["autoWait"]:
            return "{}({});".format(speaker, text)
        return "{}.say({}, false);".format(speaker, text)

    def statement(self, command):
        kind = command["type"]
        if kind == "Say":
            return self.say(command)
        if kind == "Character":
            if command["action"] != "set_state":
                raise ConvertError("Unsupported character action " + command["action"])
            effect = transition(command["transition"], "dissolve", DEFAULT_DISSOLVE)
            arguments = literal(command["state"]) + ("" if effect == "" else ", " + (effect or "none()"))
            return "{}.show({});".format(speaker_name(command["characterId"]), arguments)
        if kind == "Scene":
            effect = transition(command["transition"])
            return "scene({}{});".format(literal(command["resourceId"]), "" if effect is None else ", " + effect)
        if kind == "Audio":
            fade = float(command.get("fadeSeconds", 0))
            if command["bus"] == "Music":
                if command["action"] == "stop":
                    return "stop_music({});".format("" if fade == 0.5 else number(fade))
                arguments = [literal(command["resourceId"])]
                if fade != 1.5 or not command["loop"]:
                    arguments.append(number(fade))
                if not command["loop"]:
                    arguments.append("false")
                return "play_music({});".format(", ".join(arguments))
            if command["action"] == "stop":
                return "stop_sound({});".format("" if fade == 0.5 else number(fade))
            arguments = [literal(command["resourceId"])]
            if command["loop"] or fade != 0:
                arguments.append("true" if command["loop"] else "false")
            if fade != 0:
                arguments.append(number(fade))
            return "play_sound({});".format(", ".join(arguments))
        if kind == "NvlClear":
            return "nvl_clear();"
        if kind == "RollbackBarrier":
            return "barrier();"
        if kind == "Wait":
            if command.get("waitForInput"):
                return "wait_click();"
            return "pause({});".format(number(command.get("seconds", 0)))
        if kind == "Assign":
            name = "v." + variable_name(command["variableId"])
            value = command["value"]
            value = ("true" if value else "false") if isinstance(value, bool) else str(value)
            if command["operation"] == "set":
                return "{} = {};".format(name, value)
            if command["operation"] == "add":
                return "{} += {};".format(name, value)
            raise ConvertError("Unsupported assignment " + command["operation"])
        raise ConvertError("Unsupported command " + kind)

    def terminal_tail(self, node):
        """A short linear chain that ends the function may be duplicated (shared failure sinks in fixtures)."""
        for _ in range(8):
            command = self.story.commands[node]
            if command["type"] in ("Return", "RestartToMenu"):
                return True
            if command["type"] in ("Branch", "Choice", "Call", "Jump"):
                return False
            node = command.get("next")
            if node is None:
                return True
            if node in self.story.label_at:
                return False
        return False

    def block(self, node, stops, indent):
        """Returns (lines, terminated)."""
        lines = []
        while node not in stops:
            if node is None:
                return lines + [indent + "return;"], True
            if node in self.story.label_at and node != self.entry:
                return lines + self.transfer(node, indent), True
            if node == self.entry and node in self.emitted:
                return lines + self.transfer(node, indent), True
            if node in self.emitted and not self.terminal_tail(node):
                raise ConvertError("{}: command {} is reached twice (unstructured flow)".format(self.label, node))
            self.emitted.add(node)
            command = self.story.commands[node]
            kind = command["type"]
            if kind == "Return":
                return lines + [indent + "return;"], True
            if kind == "RestartToMenu":
                return lines + [indent + "restart_to_menu();"], True
            if kind == "Jump":
                return lines + self.transfer(command["target"], indent), True
            if kind == "Call":
                lines.append(indent + "call({});".format(self.story.function(self.story.label_at[command["target"]])))
                node = command["returnTarget"]
                continue
            if kind == "Branch":
                join = command["next"]
                inner = indent + "    "
                true_lines, true_end = self.block(command["trueTarget"], stops | {join}, inner) if command["trueTarget"] != join else ([], False)
                false_lines, false_end = self.block(command["falseTarget"], stops | {join}, inner) if command["falseTarget"] != join else ([], False)
                condition = expression(command["condition"])
                if not true_lines:
                    condition = "!(" + condition + ")"
                    true_lines, true_end, false_lines, false_end = false_lines, false_end, [], False
                lines += [indent + "if ({})".format(condition), indent + "{"] + true_lines + [indent + "}"]
                if false_lines:
                    lines += [indent + "else", indent + "{"] + false_lines + [indent + "}"]
                if true_end and false_lines and false_end:
                    return lines, True
                node = join
                continue
            if kind == "Choice":
                join = command["next"]
                self.menu_count += 1
                menu = "menu" if self.menu_count == 1 else "menu" + str(self.menu_count)
                lines.append(indent + "Menu {};".format(menu))
                for option in command["options"]:
                    condition = ", " + expression(option["condition"]) if "condition" in option else ""
                    lines.append(indent + "{}.option({}{});".format(menu, literal(option["normalizedText"]), condition))
                lines += [indent + "switch ({}.show())".format(menu), indent + "{"]
                all_end = True
                for index, option in enumerate(command["options"]):
                    inner = indent + "        "
                    body, end = self.block(option["target"], stops | {join}, inner) if option["target"] != join else ([], False)
                    all_end = all_end and end
                    lines += [indent + "    case {}:".format(index), indent + "    {"] + body
                    last = body[-1].strip() if body else ""
                    if not (last in ("return;", "continue;", "restart_to_menu();") or last.startswith("jump(")):
                        lines.append(inner + "break;")
                    lines.append(indent + "    }")
                lines.append(indent + "}")
                if all_end:
                    return lines, True
                node = join
                continue
            lines.append(indent + self.statement(command))
            node = command.get("next")
        return lines, False

    def emit(self):
        indent = "        "
        body, _ = self.block(self.entry, frozenset(), indent)
        missing = self.story.region(self.label) - self.emitted
        if missing:
            raise ConvertError("{}: commands not emitted: {}".format(self.label, sorted(missing)))
        if self.loop:
            body = ["        while (true)", "        {"] + ["    " + line for line in body] + ["        }"]
        elif body and body[-1] == indent + "return;":
            body.pop()
        source = self.story.commands[self.entry]
        location = "{}:{}".format(source.get("sourceFile", "?"), source.get("sourceLine", "?"))
        return ["    // {}".format(location), "    void {}()".format(self.story.function(self.label)), "    {"] + body + ["    }"]


def story_file(story, labels, source):
    lines = [HEADER.format(source=source), '#include "../../Scripts/Runtime/StoryApi.as"', "", "namespace Story", "{"]
    for index, label in enumerate(labels):
        if index:
            lines.append("")
        lines += Emitter(story, label).emit()
    lines.append("}")
    return "\n".join(lines) + "\n"


def vars_file(variables, source):
    lines = [HEADER.format(source=source), "namespace Story", "{",
             "    /// Story save compatibility marker; bump to reject saves made with an incompatible script.",
             '    const String Version = "script-1";', "",
             "    /// All story state. Locals in story functions are fine; anything that must survive",
             "    /// save/load and rollback has to live here (it is captured on every call boundary).",
             "    class StoryVars", "    {"]
    for variable_id, variable in variables.items():
        kind = variable["type"]
        initial = variable["initial"]
        if kind == "bool":
            lines.append("        bool {} = {};".format(variable_name(variable_id), "true" if initial else "false"))
        elif kind == "int":
            lines.append("        int {} = {};".format(variable_name(variable_id), initial))
        else:
            raise ConvertError("Unsupported variable type " + kind)
    lines += ["    }", "}"]
    return "\n".join(lines) + "\n"


def characters_file(speakers, modes, source):
    lines = [HEADER.format(source=source), '#include "../../Scripts/Runtime/StoryApi.as"', "", "namespace Story", "{",
             "    // Names, colors and voices: speakers.json; sprites and states: characters.json."]
    for speaker_id in speakers:
        mode = modes.get(speaker_id, "ADV")
        arguments = literal(speaker_id) + (", " + literal(mode) if mode != "ADV" else "")
        lines.append("    Character {}({});".format(speaker_name(speaker_id), arguments))
    lines.append("}")
    return "\n".join(lines) + "\n"


def speaker_modes(documents):
    modes = {}
    for document in documents:
        for command in document["commands"].values():
            if command["type"] != "Say":
                continue
            previous = modes.setdefault(command["speakerId"], command["mode"])
            if previous != command["mode"]:
                raise ConvertError("Speaker {} is used in both ADV and NVL".format(command["speakerId"]))
    return modes


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default=str(STORY / "Script"))
    arguments = parser.parse_args()
    output = Path(arguments.output)
    output.mkdir(parents=True, exist_ok=True)

    main_document = json.loads((STORY / "story.json").read_text(encoding="utf-8"))
    runtime_fixture = json.loads((STORY / "runtime-fixture.json").read_text(encoding="utf-8"))
    saves_fixture = json.loads((STORY / "saves-fixture.json").read_text(encoding="utf-8"))
    speakers = json.loads((STORY / "speakers.json").read_text(encoding="utf-8"))

    for fixture in (runtime_fixture, saves_fixture):
        if fixture.get("variables") != main_document["variables"]:
            raise ConvertError("Fixture variables differ from story.json; StoryVars is shared")

    story = Story(main_document)
    covered = [label for labels in MAIN_FILES.values() for label in labels]
    if sorted(covered) != sorted(story.labels):
        raise ConvertError("MAIN_FILES does not list every label exactly once")

    files = {"Vars.as": vars_file(main_document["variables"], "story.json"),
             "Characters.as": characters_file(speakers, speaker_modes([main_document, runtime_fixture, saves_fixture]), "speakers.json")}
    for name, labels in MAIN_FILES.items():
        files[name] = story_file(story, labels, "story.json")

    fixture_lines = [HEADER.format(source="runtime-fixture.json, saves-fixture.json"),
                     '#include "../../Scripts/Runtime/StoryApi.as"', "",
                     "// Development fixtures (runtime probe buttons). Not reachable from the game.", "namespace Story", "{"]
    first = True
    for prefix, document in (("fixture_runtime_", runtime_fixture), ("fixture_saves_", saves_fixture)):
        fixture = Story(document, prefix)
        for label in fixture.labels:
            if not first:
                fixture_lines.append("")
            first = False
            fixture_lines += Emitter(fixture, label).emit()
    fixture_lines.append("}")
    files["Fixtures.as"] = "\n".join(fixture_lines) + "\n"

    for name, text in files.items():
        (output / name).write_text(text, encoding="utf-8", newline="\n")
        print("wrote", output / name)


if __name__ == "__main__":
    main()
